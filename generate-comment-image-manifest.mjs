import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(fileURLToPath(import.meta.url));
const imageRoot = resolve(repoRoot, "img");
const outputPath = resolve(repoRoot, "assets/js/comment-images.js");
const appPath = resolve(repoRoot, "assets/js/app.js");
const indexPath = resolve(repoRoot, "index.html");

async function findCommentImages(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const images = await Promise.all(entries.map(async entry => {
    const fullPath = resolve(directory, entry.name);
    if (entry.isDirectory()) return findCommentImages(fullPath);
    if (!entry.isFile() || !entry.name.startsWith("scr_") || !entry.name.endsWith(".png")) return [];
    const path = relative(repoRoot, fullPath).split(sep).join("/");
    return [{ id: path.slice("img/".length), path, label: path.slice("img/".length) }];
  }));
  return images.flat();
}

const images = (await findCommentImages(imageRoot)).sort((left, right) => left.path.localeCompare(right.path));
const source = `// Generated by generate-comment-image-manifest.mjs.\n// Only img/**/scr_*.png files appear in this allowlist.\nexport const commentImages = Object.freeze(${JSON.stringify(images, null, 2)});\n`;
const version = createHash("sha256").update(source).digest("hex").slice(0, 12);
const appSource = await readFile(appPath, "utf8");
const indexSource = await readFile(indexPath, "utf8");
const versionedAppSource = appSource.replace(
  /from '\.\/comment-images\.js\?v=[^']+';/,
  `from './comment-images.js?v=comment-images-${version}';`
);
const versionedIndexSource = indexSource.replace(
  /src="\/assets\/js\/app\.js\?v=[^"]+"/,
  `src="/assets/js/app.js?v=comment-images-${version}"`
);

if (versionedAppSource === appSource && !appSource.includes(`comment-images-${version}`)) {
  throw new Error("Could not update the comment image import version in assets/js/app.js.");
}
if (versionedIndexSource === indexSource && !indexSource.includes(`comment-images-${version}`)) {
  throw new Error("Could not update the app.js version in index.html.");
}

await writeFile(outputPath, source, "utf8");
await writeFile(appPath, versionedAppSource, "utf8");
await writeFile(indexPath, versionedIndexSource, "utf8");
console.log(`Registered ${images.length} comment image(s) with cache version ${version}.`);
