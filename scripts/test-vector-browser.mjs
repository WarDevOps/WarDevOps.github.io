// Usage: node test-vector-browser.mjs <playwright/index.mjs> <sample.json> <screenshot.png>
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.argv[2]));
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1500,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error'&&m.text().includes('synchronization failed'))console.error('Browser:',m.text());});
await page.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:8137')?route.continue():route.abort());
const key='Middle East::domination-1|Red';
const layout=()=>page.evaluate(()=>Object.values(localStorage).map(s=>{try{return JSON.parse(s);}catch{return null;}}).find(s=>s?.version===2&&s?.markers));
const toolbar=page.locator('.marker-tools .vector-editor-tools');
try {
  await page.goto('http://127.0.0.1:8137/?map=Middle%20East',{waitUntil:'domcontentloaded'});
  await page.locator('#map-image').waitFor({state:'visible'});
  await page.locator('#editor-disclosure').evaluate(e=>e.open=true);
  await page.locator('#toggle-editor').click();
  await toolbar.waitFor({state:'visible'});
  const before=await layout();
  await page.locator('#vector-import-file').setInputFiles(process.argv[3]);
  await page.waitForFunction(()=>document.querySelectorAll('.vector-marker-label').length>=4);
  let after=await layout();
  assert.equal(after.markers[key].length,before.markers[key].length+4);
  assert.equal(after.annotations[key].length,before.annotations[key].length+2);
  assert.deepEqual(after.markers[key].slice(0,before.markers[key].length),before.markers[key]);
  assert.equal(after.vectorGroups[key][0].members.length,6);
  assert.equal(await page.locator('#marker-layer .is-vector-selected').count(),4);
  console.log('Additive import and automatic group selection passed');
  const originalMatrix=after.vectorGroups[key][0].matrix;
  await toolbar.locator('input[type=number]').nth(1).fill('90');
  await toolbar.locator('button').filter({hasText:'Apply size'}).click();
  after=await layout();assert.notDeepEqual(after.vectorGroups[key][0].matrix,originalMatrix);
  await toolbar.locator('[data-vector-action=undo]').click();
  assert.deepEqual((await layout()).vectorGroups[key][0].matrix,originalMatrix);
  await toolbar.locator('[data-vector-action=redo]').click();
  const scaled=await layout();
  await toolbar.locator('input[type=number]').nth(1).fill('100000');
  await toolbar.locator('button').filter({hasText:'Apply size'}).click();
  assert.deepEqual((await layout()).vectorGroups[key][0].matrix,scaled.vectorGroups[key][0].matrix);
  console.log('Scaling, undo/redo, and whole-group boundary rejection passed');
  await toolbar.locator('[data-vector-action=flipX]').click();
  await toolbar.locator('input[type=number]').first().fill('10');
  await toolbar.locator('button').filter({hasText:'Apply rotation'}).click();
  const transformed=await layout();
  assert.notDeepEqual(transformed.vectorGroups[key][0].matrix,scaled.vectorGroups[key][0].matrix);
  await toolbar.locator('[data-vector-action=clear]').click();
  assert.equal(await page.locator('#marker-layer .is-vector-selected').count(),0);
  await page.locator('#map-stage').scrollIntoViewIfNeeded();
  const rect=await page.locator('#marker-layer').boundingBox();
  await page.mouse.move(rect.x+1,rect.y+1);await page.mouse.down();
  await page.mouse.move(rect.x+rect.width-1,rect.y+rect.height-1,{steps:12});await page.mouse.up();
  assert.equal(await page.locator('#marker-layer .is-vector-selected').count(),4);
  console.log('Always-on marquee selection respects existing-object lock');
  const box=await page.locator('#map-stage .vector-box').boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  await page.mouse.move(box.x+box.width/2+8,box.y+box.height/2+5,{steps:8});await page.mouse.up();
  const moved=await layout();assert.notDeepEqual(moved.vectorGroups[key][0].matrix,transformed.vectorGroups[key][0].matrix);
  assert.deepEqual(moved.markers[key].slice(0,before.markers[key].length),before.markers[key]);
  assert.deepEqual(moved.vectorGroups[key][0].members,transformed.vectorGroups[key][0].members);
  assert.equal(errors.length,0,errors.join('\n'));
  if(process.argv[4])await page.screenshot({path:process.argv[4],fullPage:true});
  await page.reload({waitUntil:'domcontentloaded'});await page.locator('#map-image').waitFor({state:'visible'});
  assert.deepEqual((await layout()).vectorGroups[key],moved.vectorGroups[key]);
  assert.equal(await page.locator('#marker-layer .vector-marker-label').count(),4);
  // Export from the real UI, re-import the downloaded layout, and verify source matrices.
  await page.locator('#editor-disclosure').evaluate(e=>e.open=true);await page.locator('#toggle-editor').click();
  await page.evaluate(()=>{window.showSaveFilePicker=undefined;});
  const downloadPromise=page.waitForEvent('download');await page.locator('#export-marker-layout').click();
  const download=await downloadPromise;const path=await download.path();
  await page.locator('#marker-layout-import-file').setInputFiles(path);
  await page.waitForFunction(()=>document.querySelector('#marker-status').textContent.toLowerCase().includes('import'));
  assert.deepEqual((await layout()).vectorGroups[key],moved.vectorGroups[key]);
  console.log('Pointer move, unchanged source geometry, reload, and export/import round trip passed');
  await page.locator('#toggle-editor').click();
  await page.locator('#map-image').click();
  await page.locator('#image-modal').waitFor({state:'visible'});
  await page.locator('#modal-toggle-editor').click();
  const modal=page.locator('.modal-marker-tools .vector-editor-tools');
  await modal.locator('[data-vector-action=all]').click();
  assert.equal(await page.locator('#modal-marker-layer .is-vector-selected').count(),4);
  await modal.locator('input[type=number]').nth(1).fill('60');await modal.locator('button').filter({hasText:'Apply size'}).click();
  const beforeHandle=await layout();
  const handle=await page.locator('#modal-map-stage .vector-se').boundingBox();
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();
  await page.mouse.move(handle.x-15,handle.y-15,{steps:8});await page.mouse.up();
  const resized=await layout();assert.notDeepEqual(resized.vectorGroups[key][0].matrix,beforeHandle.vectorGroups[key][0].matrix);
  const rotation=await page.locator('#modal-map-stage .vector-rotate').boundingBox();
  await page.mouse.move(rotation.x+rotation.width/2,rotation.y+rotation.height/2);await page.mouse.down();
  await page.mouse.move(rotation.x+30,rotation.y+15,{steps:8});await page.mouse.up();
  assert.notDeepEqual((await layout()).vectorGroups[key][0].matrix,resized.vectorGroups[key][0].matrix);
  await modal.locator('input[type=checkbox]').uncheck();await modal.locator('[data-vector-action=all]').click();
  assert.ok(await page.locator('#modal-marker-layer .is-vector-selected').count()>4);
  await modal.locator('[data-vector-action=group]').click();
  let grouped=await layout();assert.equal(grouped.vectorGroups[key].length,1);
  assert.ok(grouped.vectorGroups[key][0].members.length>6);
  await modal.locator('[data-vector-action=undo]').click();
  assert.equal((await layout()).vectorGroups[key][0].members.length,6);
  console.log('Fullscreen corner resize, rotation handle, unlocking and grouping passed');
  // Toolbar changes resize the image's object-fit box, not the browser window.
  for (let i=0;i<4;i++) {
    await page.locator('#modal-toggle-editor').click();
    await page.waitForFunction(() => {
      const image=document.querySelector('#modal-image'),r=image.getBoundingClientRect();
      const scale=Math.min(r.width/image.naturalWidth,r.height/image.naturalHeight);
      const width=image.naturalWidth*scale,height=image.naturalHeight*scale;
      const left=r.left+(r.width-width)/2,top=r.top+(r.height-height)/2;
      return ['modal-marker-layer','modal-annotation-layer','modal-map-overlay-layer'].every(id=>{
        const b=document.getElementById(id).getBoundingClientRect();
        return Math.abs(b.left-left)<1&&Math.abs(b.top-top)<1&&Math.abs(b.width-width)<1&&Math.abs(b.height-height)<1;
      });
    });
  }
  console.log('Overlay alignment stays on the image after repeated editor toggles');
  assert.equal(errors.length,0,errors.join('\n'));
} catch(error) {
  console.error('Page errors:',errors);
  console.error('Storage:',await page.evaluate(()=>Object.entries(localStorage).map(([k,v])=>[k,v.length,v.slice(0,120)])));
  console.error(await page.locator('#toggle-editor').evaluate(e=>({text:e.textContent,pressed:e.getAttribute('aria-pressed'),viewer:document.querySelector('.map-viewer').className,panels:[...document.querySelectorAll('.vector-editor-tools')].map(p=>({hidden:p.hidden,text:p.textContent.slice(0,150)}))})).catch(()=>null));
  throw error;
} finally {await browser.close();}
